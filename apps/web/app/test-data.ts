export function getResult(answers: readonly Answer[]): Result {
  const s: Record<Axis, number> = {
    E: 0,
    I: 0,
    P: 0,
    F: 0,
    L: 0,
    H: 0,
    D: 0,
    S: 0,
  };
  questions.forEach((q, i) => s[q.axis[answers[i] ?? 0]]++);
  const code = `${s.E >= s.I ? "E" : "I"}${s.P >= s.F ? "P" : "F"}${s.L >= s.H ? "L" : "H"}${s.D >= s.S ? "D" : "S"}`;
  return results[code];
}
